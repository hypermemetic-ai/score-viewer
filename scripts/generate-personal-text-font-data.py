#!/usr/bin/env python3
"""Reproduce finite personal-reading text metrics for the existing pinned face.

Requires FontTools; no platform-font lookup or subset/modification occurs.
"""
import hashlib
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'src/LiberationSerif-Italic.ttf'
FACE_SHA = 'eaeaf7f2b12544ecde64290c1fa7ec403ff70fd58b313637b265400b20249242'
METRIC_SHA = '92fc4a612517ade11fa589ecd3babd0300c3e6eac8c48606aef2d7ae4fab58fb'
data = FONT.read_bytes()
assert hashlib.sha256(data).hexdigest() == FACE_SHA, 'Unreviewed face'
font = TTFont(FONT)
assert font['name'].getDebugName(5) == 'Version 2.1.5'
assert font['head'].unitsPerEm == 2048 and font['OS/2'].usWeightClass == 400
assert not any(t in font for t in ('fvar', 'avar', 'gvar', 'CFF2'))
cmap, glyphs, rows = font.getBestCmap(), font.getGlyphSet(), {}
for ch in map(chr, range(32, 127)):
    name = cmap[ord(ch)]
    pen = BoundsPen(glyphs)
    glyphs[name].draw(pen)
    rows[ch] = {'glyph': name, 'advance': font['hmtx'][name][0],
                'bounds': list(pen.bounds) if pen.bounds else None}
metrics = {'version': 'viewer-personal-serif-metrics-v1', 'fontSha256': FACE_SHA,
           'unitsPerEm': 2048, 'glyphs': rows,
           'verticalCell': {'head': [font['head'].yMin, font['head'].yMax],
                            'hhea': [font['hhea'].descent, font['hhea'].ascent],
                            'typo': [font['OS/2'].sTypoDescender, font['OS/2'].sTypoAscender],
                            'win': [-font['OS/2'].usWinDescent, font['OS/2'].usWinAscent]},
           'drawingAllowancePageUnits': 2}
literal = json.dumps(metrics, sort_keys=True, separators=(',', ':'))
metric_sha = hashlib.sha256(literal.encode()).hexdigest()
if METRIC_SHA: assert metric_sha == METRIC_SHA, 'Unreviewed metrics'
print('Complete cell metric SHA256:', metric_sha)
output = ('// Generated by scripts/generate-personal-text-font-data.py from the existing licensed face.\n'
          'export const PERSONAL_TEXT_METRICS_JSON=' + json.dumps(literal) + ';\n')
(ROOT / 'src/personal-text-font-data.ts').write_text(output)
print('Reproduced 95 basic Latin cmap/advance/outline records; original font bytes untouched.')
